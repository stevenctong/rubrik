  $statusLabel = $state.Status
  $color = switch ($statusLabel) {
    'Success'        { 'Green' }
    'PartialSuccess' { 'Yellow' }
    'Initiated'      { 'Cyan' }
    'Pending'        { 'DarkGray' }
    'Failed'         { 'Red' }
    default          { 'White' }
  }
  $detail = switch ($statusLabel) {
    'Initiated'      { "async: $($state.AsyncRequestId)" }
    'Failed'         { $state.ErrorMessage }
    'Success'        { $state.LastMessage }
    'PartialSuccess' { $state.LastMessage }
    default          { $state.Drives }
  }
  Write-Host "  [$statusLabel] $($state.SourceHostname) -> $($state.TargetHost): $detail" -ForegroundColor $color
}

